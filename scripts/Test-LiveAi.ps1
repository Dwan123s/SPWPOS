param([switch]$SkipBuild, [switch]$Quality)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'Initialize-Dotnet.ps1')
$taskAiRoot = Split-Path -Parent $PSScriptRoot
$taskAiProject = Join-Path $taskAiRoot 'src\SPWPOS.Api\SPWPOS.Api.csproj'
$taskAiResultPath = Join-Path $taskAiRoot 'artifacts\cloud-ai-check.result.json'
$taskAiLogPath = Join-Path $taskAiRoot 'artifacts\cloud-ai-check.log'
$taskAiAssemblyDirectory = Join-Path $taskAiRoot 'src\SPWPOS.Api\bin\Release\net8.0'
[IO.Directory]::CreateDirectory((Split-Path -Parent $taskAiResultPath)) | Out-Null
@{ success = $false; code = 'CHECK_NOT_FINISHED'; time = [DateTimeOffset]::UtcNow.ToString('O') } |
    ConvertTo-Json -Compress | Set-Content -LiteralPath $taskAiResultPath -Encoding UTF8
if (-not $SkipBuild) {
    # Diagnostics must not terminate another checkout or overwrite a serving API.
    $taskAiAssemblyDirectory = Join-Path $taskAiRoot 'artifacts\ai-diagnostics\net8.0'
    & $SpwposDotnet build $taskAiProject -c Release --no-restore -m:1 -p:SkipFrontendBuild=true -p:UseSharedCompilation=false "-p:OutputPath=$taskAiAssemblyDirectory"
    if ($LASTEXITCODE -ne 0) { throw 'AI diagnostics build failed.' }
}
$env:ASPNETCORE_ENVIRONMENT = 'Development'
Push-Location -LiteralPath (Split-Path -Parent $taskAiProject)
try {
    # Windows PowerShell 5.1 wraps stderr as ErrorRecords. Capture both streams
    # without stopping before the sanitized diagnostic has been recorded.
    $taskAiOldErrorPreference = $ErrorActionPreference
    try {
        $ErrorActionPreference = 'Continue'
        $taskAiMode = if ($Quality) { '--check-ai-quality' } else { '--check-ai' }
        $taskAiRawOutput = @(& $SpwposDotnet (Join-Path $taskAiAssemblyDirectory 'SPWPOS.Api.dll') $taskAiMode 2>&1)
        $taskAiExitCode = $LASTEXITCODE
    } finally { $ErrorActionPreference = $taskAiOldErrorPreference }
    # Only lines generated by LiveAiCheck/Program are safe for the setup log.
    # Never copy raw native errors, response bodies or credential values.
    $taskAiSafeLines = @($taskAiRawOutput | ForEach-Object {
        [regex]::Matches("$_", '(?m)^LIVE AI[^\r\n]*') | ForEach-Object { $_.Value }
    })
    $taskAiRawOutput = $null
    $taskAiFailureCode = 'CHECK_FAILED'
    $taskAiProviderReason = $null
    $taskAiHttpStatus = $null
    foreach ($taskAiSafeLine in $taskAiSafeLines) {
        if ($taskAiSafeLine -match '^LIVE AI check failed: ([A-Z][A-Z0-9_]+)\.') { $taskAiFailureCode = $Matches[1] }
        if ($taskAiSafeLine -match '^LIVE AI provider detail: HTTP=([0-9]{3}); REASON=([A-Z][A-Z0-9_]{0,79})\.') {
            $taskAiHttpStatus = [int]$Matches[1]; $taskAiProviderReason = $Matches[2]
        }
    }
    if ($taskAiSafeLines.Count -eq 0) {
        $taskAiFailureCode = 'AI_STARTUP_FAILED'
        $taskAiSafeLines = @('LIVE AI check failed: AI_STARTUP_FAILED. Backend diagnostics did not return a safe result.')
    }
    $taskAiSafeLines | Set-Content -LiteralPath $taskAiLogPath -Encoding UTF8
    $taskAiSafeLines | ForEach-Object { Write-Host $_ }
    $taskAiPassed = $taskAiExitCode -eq 0 -and $taskAiSafeLines.Count -gt 0 -and
        [bool]($taskAiSafeLines -match $(if ($Quality) { 'quality checks passed' } else { 'structured output and planner checks passed' }))
    @{ success = $taskAiPassed; code = $(if ($taskAiPassed) { 'OK' } else { $taskAiFailureCode });
        providerReason = $taskAiProviderReason; httpStatus = $taskAiHttpStatus;
        time = [DateTimeOffset]::UtcNow.ToString('O') } | ConvertTo-Json -Compress |
        Set-Content -LiteralPath $taskAiResultPath -Encoding UTF8
    if (-not $taskAiPassed) { throw 'Live AI verification did not pass. See artifacts/cloud-ai-check.log.' }
} finally { Pop-Location }
